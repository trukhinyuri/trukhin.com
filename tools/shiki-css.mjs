#!/usr/bin/env node
// Writes dist/shiki.css from the Shiki colour classes used in dist (src/lib/shiki-classes.mjs).
// Each class name encodes its value, so the stylesheet is derived from the build, sorted and deterministic.
import { writeFileSync } from 'node:fs';
import { DIST, distFiles, read, join } from './lib.mjs';
import { CLASS_TO_PROP } from '../src/lib/shiki-classes.mjs';

const used = new Set();
for (const f of distFiles().filter((f) => f.endsWith('.html'))) {
  for (const [, cls] of read(join(DIST, f)).matchAll(/class="([^"]*astro-code[^"]*|[^"]*\bs[ld][a-z]*-[0-9a-z-]+[^"]*)"/g)) {
    for (const c of cls.split(/\s+/)) if (/^s[ld][a-z]*-[0-9a-z-]+$/.test(c)) used.add(c);
  }
}
const rules = [];
for (const c of [...used].sort()) {
  const i = c.indexOf('-');
  const prop = CLASS_TO_PROP[c.slice(0, i)];
  if (!prop) continue;
  const raw = c.slice(i + 1);
  const value = /font|decoration/.test(prop) ? raw : `#${raw}`;
  rules.push(`.${c}{${prop}:${value}}`);
}
writeFileSync(join(DIST, 'shiki.css'), `/* Generated by tools/shiki-css.mjs from the classes used in this build. */\n${rules.join('\n')}\n`);
console.log(`shiki.css: ${rules.length} classes`);
